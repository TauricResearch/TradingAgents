"""Shared evidence-side contracts: ``RunSpec``, ``EvidenceItem``, ``EvidencePack``.

# Implements: FR-01, INV-02

Type-layer only. These models fix the SHAPE the evidence module (A) produces and
its consumers read; they do NOT filter by time, generate ids, dedupe, or compare
digests at pack time. Those behaviours belong to ``egta.evidence`` (A):

- ``evidence_id`` is generated by the evidence module from the run id + case local
  id; these types store the id they are given and never mint one.
- the UTC date filter (strictly-earlier admitted / same-date excluded / exact
  timestamp equality admitted) is A's; these types only carry its outcomes.
- ``content_hash`` is NOT cross-validated against ``excerpt`` here, so a tampered
  item is constructible; the evidence module recomputes and reports
  ``INTEGRITY_VIOLATION`` at pack time.

The shared ``ReasonCode`` is owned by the contracts package's events module; this
module imports it rather than defining a second enum.
"""

from __future__ import annotations

import re
from datetime import UTC, date, datetime
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator

from egta.contracts.events import ReasonCode

_HASH_PATTERN = r"^[0-9a-f]{64}$"
_DATE_ONLY = re.compile(r"^\d{4}-\d{2}-\d{2}$")


class Availability(StrEnum):
    """Admission state of an evidence item.

    Distinct from ``ReasonCode``: ``availability`` is the state, ``reason_code`` is
    the cause. They are independent and neither substitutes for the other.
    """

    AVAILABLE = "available"
    STALE = "stale"
    UNREACHABLE = "unreachable"
    UNAVAILABLE = "unavailable"


def _normalize_time(value: Any) -> Any:
    """Normalize an evidence timestamp for ``published_at`` / ``fetched_at``.

    A bare ``YYYY-MM-DD`` is kept as a ``date`` so day precision survives to the
    public JSON form (no invented time or offset). Any other string is parsed as a
    datetime; a timezone-aware value is converted to UTC, and a naive one is kept
    as given. The contract frozen for these types does not require rejecting a naive
    evidence timestamp, so this function does not reject one here: deciding whether
    an evidence time is admissible (including a naive or malformed value) is A's
    ``egta.evidence`` time-policy responsibility, not this type's.
    """
    if isinstance(value, str):
        if _DATE_ONLY.fullmatch(value):
            return date.fromisoformat(value)
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        return parsed.astimezone(UTC) if parsed.tzinfo is not None else parsed
    if isinstance(value, datetime):
        return value.astimezone(UTC) if value.tzinfo is not None else value
    return value


class RunSpec(BaseModel):
    """Run definition shared by every module (plan §5.1).

    ``as_of`` is the analysis instant: a timezone-aware UTC datetime. A bare date
    or a naive timestamp is rejected (evidence may be date-only; ``as_of`` may not).
    """

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    schema_version: str
    run_id: str = Field(min_length=1)
    ticker: str = Field(min_length=1)
    as_of: datetime
    mode: str
    model_config_hash: str = Field(pattern=_HASH_PATTERN)
    prompt_hash: str = Field(pattern=_HASH_PATTERN)
    policy_hash: str = Field(pattern=_HASH_PATTERN)
    snapshot_id: str = Field(min_length=1)
    limits: dict[str, Any]

    @field_validator("as_of", mode="before")
    @classmethod
    def _require_aware_instant(cls, value: Any) -> Any:
        # Reject a bare date string outright: as_of must be an instant.
        if isinstance(value, str) and _DATE_ONLY.fullmatch(value):
            raise ValueError("as_of must be a timezone-aware datetime, not a bare date")
        return value

    @field_validator("as_of")
    @classmethod
    def _as_of_aware_utc(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("as_of must be timezone-aware (UTC)")
        return value.astimezone(UTC)


class EvidenceItem(BaseModel):
    """One admitted or excluded evidence item (plan §5.1).

    ``availability`` is required and enumerated. ``reason_code`` and
    ``conflict_group`` default to ``None``. ``published_at`` accepts a date-only
    value (kept as a date) or a full timestamp.
    """

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    evidence_id: str = Field(min_length=1)
    source_uri: str = Field(min_length=1)
    published_at: date | datetime
    fetched_at: date | datetime
    content_hash: str = Field(pattern=_HASH_PATTERN)
    excerpt: str
    availability: Availability
    trust_label: str
    reason_code: ReasonCode | None = None
    conflict_group: str | None = None

    @field_validator("published_at", "fetched_at", mode="before")
    @classmethod
    def _keep_day_precision(cls, value: Any) -> Any:
        return _normalize_time(value)


class ExcludedItem(BaseModel):
    """A pack exclusion: exactly the three agreed fields.

    Not an ``EvidenceItem``: no ``published_at`` and no full ``evidence_id``.
    ``case_local_id == "provider"`` marks a provider-level failure. Provider error
    detail is recorded by the evidence module in the audit payload, not here.
    """

    model_config = ConfigDict(extra="forbid")

    case_local_id: str = Field(min_length=1)
    availability: Availability
    reason_code: ReasonCode


class EvidencePack(BaseModel):
    """The evidence module's output for one run (plan §5.1).

    ``excluded_items`` is required (an explicit empty list is valid; omitting it
    fails). ``cutoff`` is the same instant as the run/fixture ``as_of``.
    ``pack_hash`` is carried as supplied; its algorithm is not frozen here.
    """

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    run_id: str = Field(min_length=1)
    snapshot_id: str = Field(min_length=1)
    items: list[EvidenceItem]
    excluded_items: list[ExcludedItem]
    cutoff: datetime
    pack_hash: str = Field(pattern=_HASH_PATTERN)

    @field_validator("cutoff")
    @classmethod
    def _cutoff_aware_utc(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("cutoff must be timezone-aware (UTC)")
        return value.astimezone(UTC)
