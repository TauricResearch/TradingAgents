const stored = typeof window === 'undefined' ? null : window.localStorage.getItem(UI_LANGUAGE_KEY)
const initialLanguage = stored === 'zh' || stored === 'en' ? stored : 'en'

void i18n.use(initReactI18next).init({
  resources: { en: { translation: en }, zh: { translation: zh } },
  lng: initialLanguage,
  fallbackLng: 'en',
  keySeparator: false,
  interpolation: { escapeValue: false },
})

export function setUiLanguage(language: 'en' | 'zh') {
  window.localStorage.setItem(UI_LANGUAGE_KEY, language)
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en'
  return i18n.changeLanguage(language)
}

document.documentElement.lang = initialLanguage === 'zh' ? 'zh-CN' : 'en'

